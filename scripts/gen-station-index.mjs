// Builds assets/js/data/ep-stations.js: the TMY3 weather files EnergyPlus distributes in
// its GitHub repository (CORS-enabled raw URLs), with the coordinates, elevation and
// source read from each file's own LOCATION header.   node scripts/gen-station-index.mjs
import { writeFileSync } from 'node:fs';
const REF = 'develop';
const list = await (await fetch(`https://api.github.com/repos/NREL/EnergyPlus/contents/weather?ref=${REF}`, { headers: { 'User-Agent': 'bim2bem-station-index' } })).json();
if (!Array.isArray(list)) throw new Error(`GitHub API: ${JSON.stringify(list).slice(0, 200)}`);
const out = [];
for (const f of list.filter(x => /\.epw$/i.test(x.name))) {
  const url = `https://raw.githubusercontent.com/NREL/EnergyPlus/${REF}/weather/${f.name}`;
  const text = await (await fetch(url, { headers: { Range: 'bytes=0-2000' } })).text();
  const loc = text.split(/\r?\n/)[0].split(',');
  const comment = (text.split(/\r?\n/).find(l => /^COMMENTS 1/.test(l)) || '').replace(/^COMMENTS 1,/, '').trim();
  // Real station files only: TMY3 records (EnergyPlus also ships synthetic test weather).
  if (loc[4] !== 'TMY3' || /\s/.test(f.name) || !(Math.abs(+loc[6]) <= 90)) continue;
  out.push({ file: f.name, url, name: loc[1], region: loc[2], country: loc[3], source: loc[4], wmo: loc[5], latitude: +loc[6], longitude: +loc[7], timeZone: +loc[8], elevation: +loc[9], period: comment.slice(0, 160), bytes: f.size });
}
writeFileSync(new URL('../assets/js/data/ep-stations.js', import.meta.url), `/* Generated by scripts/gen-station-index.mjs from github.com/NREL/EnergyPlus/tree/${REF}/weather. */\nwindow.EP_STATIONS = ${JSON.stringify(out, null, 0)};\n`);
console.log(`Indexed ${out.length} weather files`);
