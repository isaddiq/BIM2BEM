// Extracts the EnergyPlus object definitions BIM2BEM writes from the official
// Energy+.schema.epJSON shipped in @idfkit/engine-assets, so the IDF writer uses the
// engine's own field order and the browser can validate a model before running it.
//
//   node scripts/gen-ep-schema.mjs
//
// Output: assets/js/data/ep-schema.js (window.EP_SCHEMA). Re-run after upgrading
// @idfkit/engine-assets so the field order always matches the bundled engine.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const assetsPkg = require('@idfkit/engine-assets/package.json');
const schemaPath = require.resolve('@idfkit/engine-assets/assets/Energy+.schema.epJSON');
const schema = JSON.parse(readFileSync(schemaPath, 'utf8'));

const OBJECTS = [
  'Version', 'SimulationControl', 'Building', 'Timestep', 'RunPeriod', 'Site:Location',
  'GlobalGeometryRules', 'ShadowCalculation', 'SurfaceConvectionAlgorithm:Inside', 'SurfaceConvectionAlgorithm:Outside',
  'HeatBalanceAlgorithm', 'ZoneAirHeatBalanceAlgorithm', 'ZoneAirContaminantBalance', 'Site:GroundTemperature:BuildingSurface',
  'Foundation:Kiva', 'Foundation:Kiva:Settings', 'SurfaceProperty:ExposedFoundationPerimeter',
  'ScheduleTypeLimits', 'Schedule:Compact', 'Schedule:Constant',
  'Material', 'Material:NoMass', 'Material:AirGap', 'WindowMaterial:SimpleGlazingSystem', 'Construction',
  'Zone', 'BuildingSurface:Detailed', 'FenestrationSurface:Detailed', 'Shading:Site:Detailed', 'Shading:Building:Detailed',
  'People', 'Lights', 'ElectricEquipment', 'ZoneInfiltration:DesignFlowRate', 'ZoneVentilation:WindandStackOpenArea',
  'DesignSpecification:OutdoorAir', 'ZoneHVAC:IdealLoadsAirSystem', 'ZoneHVAC:EquipmentList', 'ZoneHVAC:EquipmentConnections',
  'ZoneControl:Thermostat', 'ThermostatSetpoint:DualSetpoint',
  'Daylighting:Controls', 'Daylighting:ReferencePoint',
  'Output:Variable', 'Output:Meter', 'Output:VariableDictionary', 'Output:Table:SummaryReports', 'OutputControl:Table:Style',
  'Output:SQLite', 'Output:Diagnostics',
];

const out = {};
for (const type of OBJECTS) {
  const def = schema.properties[type];
  if (!def) throw new Error(`Object ${type} is not in the EnergyPlus ${assetsPkg.version} schema`);
  const idd = def.legacy_idd;
  const props = (def.patternProperties && Object.values(def.patternProperties)[0].properties) || {};
  const required = (def.patternProperties && Object.values(def.patternProperties)[0].required) || [];
  const extName = idd.extension || null;
  const extProps = extName && props[extName] && props[extName].items ? props[extName].items.properties : {};
  const describe = (p) => {
    if (!p) return {};
    const d = {};
    const t = p.type || (p.anyOf ? p.anyOf.map(a => a.type || (a.enum ? 'enum' : '')).filter(Boolean) : null);
    if (t) d.t = t;
    const en = p.enum || (p.anyOf && p.anyOf.flatMap(a => a.enum || []));
    if (en && en.length) d.e = en.filter(x => x !== '');
    for (const k of ['minimum', 'maximum', 'exclusiveMinimum', 'exclusiveMaximum']) if (p[k] != null) d[k] = p[k];
    if (p.default != null) d.d = p.default;
    return d;
  };
  const fields = idd.fields.map(f => [f, describe(f === 'name' ? { type: 'string' } : props[f])]);
  const ext = (idd.extensibles || []).map(f => [f, describe(extProps[f])]);
  out[type] = {
    fields,
    ext,
    extName,
    required: required.filter(r => r !== 'name'),
    named: !!def.name,
    unique: !!def.maxProperties && def.maxProperties === 1,
    minFields: def.min_fields || 0,
  };
}

mkdirSync(new URL('../assets/js/data/', import.meta.url), { recursive: true });
const banner = `/* Generated by scripts/gen-ep-schema.mjs from Energy+.schema.epJSON (EnergyPlus ${assetsPkg.version}). Do not edit. */\n`;
const body = `window.EP_SCHEMA = ${JSON.stringify({ version: assetsPkg.version, objects: out })};\n`;
writeFileSync(new URL('../assets/js/data/ep-schema.js', import.meta.url), banner + body);
console.log(`Wrote ${Object.keys(out).length} object definitions for EnergyPlus ${assetsPkg.version}`);
